#!/usr/bin/env python3
# Writes Sources/Terminal/Font/NerdFontConstraints.swift from Ghostty's generated src/font/nerd_font_tables.zig, the
# path to which is the only argument: its three-stage lookup flattened into ranges of codepoints that share a
# constraint, and each constraint as a Swift value.
import pathlib
import re
import sys

LOCK = pathlib.Path(__file__).resolve().parents[2] / "vendor" / "libghostty-vt.lock"
# The Ghostty commit the tables come from is the one the lock pins, shortened as Ghostty's tip builds name it.
COMMIT = re.search(r"^commit = (\w{8})", LOCK.read_text(), re.M).group(1)
# Swift's memberwise initialiser takes the fields in the order `Constraint` declares them.
FIELDS = ["size", "align_vertical", "align_horizontal", "pad_top", "pad_left", "pad_right", "pad_bottom",
          "relative_width", "relative_height", "relative_x", "relative_y", "max_xy_ratio", "max_constraint_width",
          "height"]


def camel(name):
    if name == "max_xy_ratio":
        return "maxXYRatio"
    head, *rest = name.split("_")
    return head + "".join(part.capitalize() for part in rest)


def main(path):
    src = open(path).read()

    def stage(name):
        body = re.search(r"pub const %s: \[\d+\]u16 = \.\{([^}]*)\}" % name, src).group(1)
        return [int(x) for x in body.replace(" ", "").split(",") if x]

    stage1, stage2 = stage("stage1"), stage("stage2")
    body = src[src.index("pub const stage3"):]
    count = int(re.match(r"pub const stage3: \[(\d+)\]", body).group(1))
    body = body[body.index(".{") + 2:]
    entries = []
    for m in re.finditer(r"null|\.\{(.*?)\n            \}", body, re.S):
        entries.append(None if m.group(0) == "null" else dict(re.findall(r"\.(\w+) = ([^,\n]+),", m.group(1))))
        if len(entries) == count:
            break
    assert len(entries) == count and entries[0] is None and all(entries[1:])
    assert all(set(e) <= set(FIELDS) for e in entries[1:]), "a field Constraint lacks"

    ranges = []
    for cp in range(0x110000):
        index = stage2[stage1[cp >> 8] + (cp & 0xFF)]
        if index == 0:
            continue
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == index:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, index])

    def value(raw):
        return "." + camel(raw[1:]) if raw.startswith(".") else raw

    out = [
        "// swift-format-ignore-file",
        "// Generated by Tools/nerd-font/generate.py from Ghostty's `src/font/nerd_font_tables.zig` at commit "
        f"{COMMIT}.",
        "// Do not edit by hand.",
        "// Ghostty: MIT License, Copyright (c) 2024 Mitchell Hashimoto, Ghostty contributors; "
        "see vendor/LICENSE-ghostty.",
        "",
        "/// Every constraint Ghostty's table names.",
        "let nerdFontConstraints: [Constraint] = [",
    ]
    for e in entries[1:]:
        args = ", ".join(f"{camel(f)}: {value(e[f])}" for f in FIELDS if f in e)
        out.append(f"    Constraint({args}),")
    out += [
        "]",
        "",
        "/// Ascending ranges of codepoints that share a constraint, three numbers each: the first codepoint, "
        "the last, and",
        "/// the constraint's index in `nerdFontConstraints`. One flat array of numbers keeps the type checker "
        "fast.",
        "let nerdFontRanges: [UInt32] = [",
    ]
    for lo, hi, index in ranges:
        out.append(f"    0x{lo:X}, 0x{hi:X}, {index - 1},")
    out.append("]")
    print("\n".join(out))


main(sys.argv[1])
